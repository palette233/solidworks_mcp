#!/usr/bin/env python3
"""Generate a small, solver-validated A100/A200 repair candidate set.

The script perturbs a previous solver result only to seed the search. Every
emitted candidate is regenerated by the normal source-independent solver and
therefore still satisfies its process, spatial, and interaction constraints.
It does not claim CAD clearance; A100/A200 leaf B-Rep remains the first gate.
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
import time
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
BACKEND_SRC = ROOT / "apps" / "demo-backend" / "src"
sys.path.insert(0, str(BACKEND_SRC))

from demo_backend.constraint_layout import (  # noqa: E402
    ConstraintLayoutError,
    generate_constraint_layout,
)
from demo_backend.layout_preview import (  # noqa: E402
    _materialize_solution,
    build_source_independent_options,
)


A100 = "FL9A24D062A100.001-1"
A180 = "FL9A24D062A180.001-1"
A200 = "FL9A24D062A200.001-1"
A300 = "FL9A24D062A300.001-1"
A500 = "FL9A24D062A500.001-1"
A700 = "FL9A24D062A700.001-1"
A800 = "FL9A24D062A800.001-1"
T401 = "T401AA-07388-0-1"
DEFAULT_OFFSETS = (
    (0.110, 0.0),
    (0.125, 0.0),
    (0.140, 0.0),
    (0.140, 0.015),
    (0.140, -0.015),
    (0.155, 0.0),
)


def resolved(value: str | Path) -> Path:
    path = Path(value)
    return path if path.is_absolute() else ROOT / path


def normalized_seed(document: dict[str, Any]) -> dict[str, Any]:
    components = copy.deepcopy(document.get("components") or [])
    by_name = {item.get("componentName"): item for item in components}
    if A100 not in by_name or A200 not in by_name:
        raise ValueError("Repair seed must contain both A100 and A200.")
    gantry_layout = by_name[A100].get("layout2d") or {}
    gantry_x = float(gantry_layout["x"])
    gantry_y = float(gantry_layout["y"])
    seed_components: list[dict[str, Any]] = []
    for item in components:
        layout = item.get("layout2d") or {}
        seed_components.append(
            {
                "componentName": item["componentName"],
                "layout2d": {
                    "x": float(layout["x"]) - gantry_x,
                    "y": float(layout["y"]) - gantry_y,
                    "thetaDegrees": float(layout.get("thetaDegrees", 0.0)),
                    "thetaAxis": layout.get("thetaAxis", "x"),
                },
            }
        )
    return {
        "schemaVersion": 1,
        "purpose": "A100/A200 bounded two-dimensional repair warm start",
        "components": seed_components,
    }


def parse_offsets(
    values: list[str] | None,
    *,
    preserve_a200: bool = False,
) -> tuple[tuple[float, float], ...]:
    if not values:
        if preserve_a200:
            return ((0.0, 0.0),)
        return DEFAULT_OFFSETS
    result: list[tuple[float, float]] = []
    for value in values:
        parts = value.split(",")
        if len(parts) != 2:
            raise ValueError(f"Offset must use DU,DV syntax: {value}")
        result.append((float(parts[0]), float(parts[1])))
    return tuple(result)


def parse_single_offset(value: str | None) -> tuple[float, float]:
    if not value:
        return (0.0, 0.0)
    parts = value.split(",")
    if len(parts) != 2:
        raise ValueError(f"Offset must use DU,DV syntax: {value}")
    return (float(parts[0]), float(parts[1]))


def placement_key(solution: dict[str, Any]) -> tuple[tuple[str, float, float, float], ...]:
    return tuple(
        sorted(
            (
                str(item["componentName"]),
                round(float(item["x"]), 6),
                round(float(item["y"]), 6),
                round(float(item.get("thetaDegrees", 0.0)), 6),
            )
            for item in solution.get("placements") or []
        )
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--request",
        default="demo/FL9A24D062A000_real_process_request.json",
    )
    parser.add_argument(
        "--base-layout",
        default="demo/layout_previews/project02_selected_solution_replay_v5.json",
    )
    parser.add_argument(
        "--output-dir",
        default="demo/layout_previews/a100_a200_repair_candidates_v2",
    )
    parser.add_argument(
        "--offset",
        action="append",
        help="A200 warm-seed offset relative to A100 in solver U,V meters; repeatable.",
    )
    parser.add_argument(
        "--maximum-portal-center-offset",
        type=float,
        help=(
            "Calibration-only override for maximumPortalGantryCenterOffsetMeters. "
            "The canonical request is not modified."
        ),
    )
    parser.add_argument(
        "--t401-offset",
        help="Optional fixed T401 glue-supply DU,DV offset.",
    )
    parser.add_argument(
        "--a180-offset",
        help="Optional fixed A180 scanner DU,DV offset.",
    )
    parser.add_argument(
        "--a800-offset",
        help=(
            "Optional fixed A800 warm-seed offset in solver DU,DV meters. "
            "When set, A800 is treated as a coordinated repair target and locked."
        ),
    )
    parser.add_argument(
        "--a500-offset",
        help=(
            "Optional fixed A500 warm-seed offset in solver DU,DV meters. "
            "When set, A500 is treated as a coordinated repair target and locked."
        ),
    )
    parser.add_argument("--a300-offset", help="Optional fixed A300 DU,DV offset.")
    parser.add_argument("--a700-offset", help="Optional fixed A700 DU,DV offset.")
    args = parser.parse_args()

    request_path = resolved(args.request)
    base_path = resolved(args.base_layout)
    output_dir = resolved(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    request = json.loads(request_path.read_text(encoding="utf-8"))
    base = json.loads(base_path.read_text(encoding="utf-8"))
    geometry_path = resolved(request["geometryCapturePath"])
    capture = json.loads(geometry_path.read_text(encoding="utf-8"))
    base_seed = normalized_seed(base)
    base_a200 = next(
        item for item in base_seed["components"] if item["componentName"] == A200
    )["layout2d"]
    base_relative = {
        item["componentName"]: (
            float(item["layout2d"]["x"]),
            float(item["layout2d"]["y"]),
        )
        for item in base_seed["components"]
    }
    a800_offset = parse_single_offset(args.a800_offset)
    t401_offset = parse_single_offset(args.t401_offset)
    a180_offset = parse_single_offset(args.a180_offset)
    a500_offset = parse_single_offset(args.a500_offset)
    a300_offset = parse_single_offset(args.a300_offset)
    a700_offset = parse_single_offset(args.a700_offset)
    coordinated_a800_repair = args.a800_offset is not None
    coordinated_t401_repair = args.t401_offset is not None
    coordinated_a180_repair = args.a180_offset is not None
    coordinated_a500_repair = args.a500_offset is not None
    coordinated_a300_repair = args.a300_offset is not None
    coordinated_a700_repair = args.a700_offset is not None
    preserve_a200 = any(
        (
            coordinated_a800_repair,
            coordinated_t401_repair,
            coordinated_a180_repair,
            coordinated_a500_repair,
            coordinated_a300_repair,
            coordinated_a700_repair,
        )
    ) and args.offset is None
    a200_offsets = parse_offsets(args.offset, preserve_a200=preserve_a200)
    unlocked_names = {A100}
    if not coordinated_t401_repair:
        unlocked_names.add(T401)
    if not coordinated_a800_repair:
        unlocked_names.add(A800)
    solver_locked_components = tuple(
        sorted(
            name
            for name in base_relative
            if name not in unlocked_names
        )
    )
    repair_targets = {A200}
    if coordinated_t401_repair:
        repair_targets.add(T401)
    if coordinated_a180_repair:
        repair_targets.add(A180)
    if coordinated_a800_repair:
        repair_targets.add(A800)
    if coordinated_a500_repair:
        repair_targets.add(A500)
    if coordinated_a300_repair:
        repair_targets.add(A300)
    if coordinated_a700_repair:
        repair_targets.add(A700)
    monitored_non_target_components = tuple(
        sorted(name for name in base_relative if name not in ({A100} | repair_targets))
    )

    manifest_candidates: list[dict[str, Any]] = []
    seen: set[tuple[tuple[str, float, float, float], ...]] = set()
    for index, (delta_u, delta_v) in enumerate(a200_offsets, start=1):
        seed = copy.deepcopy(base_seed)
        a200_seed = next(
            item for item in seed["components"] if item["componentName"] == A200
        )["layout2d"]
        a200_seed["x"] = float(a200_seed["x"]) + delta_u
        a200_seed["y"] = float(a200_seed["y"]) + delta_v
        if coordinated_a800_repair:
            a800_seed = next(
                item for item in seed["components"] if item["componentName"] == A800
            )["layout2d"]
            a800_seed["x"] = float(a800_seed["x"]) + a800_offset[0]
            a800_seed["y"] = float(a800_seed["y"]) + a800_offset[1]
        if coordinated_a180_repair:
            a180_seed = next(
                item for item in seed["components"] if item["componentName"] == A180
            )["layout2d"]
            a180_seed["x"] = float(a180_seed["x"]) + a180_offset[0]
            a180_seed["y"] = float(a180_seed["y"]) + a180_offset[1]
        if coordinated_t401_repair:
            t401_seed = next(
                item for item in seed["components"] if item["componentName"] == T401
            )["layout2d"]
            t401_seed["x"] = float(t401_seed["x"]) + t401_offset[0]
            t401_seed["y"] = float(t401_seed["y"]) + t401_offset[1]
        if coordinated_a500_repair:
            a500_seed = next(
                item for item in seed["components"] if item["componentName"] == A500
            )["layout2d"]
            a500_seed["x"] = float(a500_seed["x"]) + a500_offset[0]
            a500_seed["y"] = float(a500_seed["y"]) + a500_offset[1]
        for component_name, component_offset, enabled in (
            (A300, a300_offset, coordinated_a300_repair),
            (A700, a700_offset, coordinated_a700_repair),
        ):
            if not enabled:
                continue
            component_seed = next(
                item
                for item in seed["components"]
                if item["componentName"] == component_name
            )["layout2d"]
            component_seed["x"] = float(component_seed["x"]) + component_offset[0]
            component_seed["y"] = float(component_seed["y"]) + component_offset[1]
        seed_path = output_dir / f"seed_{index:02d}.json"
        seed_path.write_text(
            json.dumps(seed, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )

        candidate_request = copy.deepcopy(request)
        policy = candidate_request.setdefault("sourceIndependentPolicy", {})
        if args.maximum_portal_center_offset is not None:
            policy["maximumPortalGantryCenterOffsetMeters"] = float(
                args.maximum_portal_center_offset
            )
        policy["warmStartKind"] = "previousSolverReplayResult"
        policy["warmStartReplayResultPath"] = str(seed_path)
        policy["warmStartLockedComponents"] = list(solver_locked_components)
        policy["maximumLayoutSolutions"] = 1
        started = time.perf_counter()
        try:
            generated = generate_constraint_layout(
                capture,
                build_source_independent_options(candidate_request, ROOT),
            )
        except ConstraintLayoutError as exc:
            elapsed = time.perf_counter() - started
            manifest_candidates.append(
                {
                    "seedIndex": index,
                    "seedOffsetMeters": [delta_u, delta_v],
                    "seedA200RelativeToA100Meters": [
                        float(base_a200["x"]) + delta_u,
                        float(base_a200["y"]) + delta_v,
                    ],
                    "seedPath": str(seed_path),
                    "solverFeasible": False,
                    "solveSeconds": elapsed,
                    "failureReason": str(exc),
                }
            )
            continue
        elapsed = time.perf_counter() - started
        joint = (generated.get("constraintPlan") or {}).get("jointSearch") or {}
        solutions = joint.get("solutions") or []
        if not solutions:
            manifest_candidates.append(
                {
                    "seedIndex": index,
                    "seedOffsetMeters": [delta_u, delta_v],
                    "seedPath": str(seed_path),
                    "solverFeasible": False,
                    "solveSeconds": elapsed,
                }
            )
            continue

        selected = solutions[0]
        key = placement_key(selected)
        duplicate = key in seen
        if not duplicate:
            seen.add(key)
        materialized = _materialize_solution(generated, selected)
        materialized["repairCandidate"] = {
            "targets": sorted(repair_targets),
            "seedOffsetMeters": [delta_u, delta_v],
            "a800SeedOffsetMeters": list(a800_offset),
            "a180SeedOffsetMeters": list(a180_offset),
            "t401SeedOffsetMeters": list(t401_offset),
            "a500SeedOffsetMeters": list(a500_offset),
            "a300SeedOffsetMeters": list(a300_offset),
            "a700SeedOffsetMeters": list(a700_offset),
            "seedPath": str(seed_path),
            "solverValidated": True,
            "requiresCadGates": [
                "A100-A200 leaf B-Rep",
                "A200-A800 leaf B-Rep",
            ],
            "productionReady": False,
        }
        solution_path = output_dir / f"candidate_{index:02d}_solution.json"
        solution_path.write_text(
            json.dumps(materialized, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        placements = {item["componentName"]: item for item in selected["placements"]}
        relative_u = float(placements[A200]["x"]) - float(placements[A100]["x"])
        relative_v = float(placements[A200]["y"]) - float(placements[A100]["y"])
        non_target_drift = {
            name: (
                (
                    float(placements[name]["x"])
                    - float(placements[A100]["x"])
                    - base_relative[name][0]
                )
                ** 2
                + (
                    float(placements[name]["y"])
                    - float(placements[A100]["y"])
                    - base_relative[name][1]
                )
                ** 2
            )
            ** 0.5
            for name in monitored_non_target_components
            if name in placements
        }
        maximum_non_target_drift = max(non_target_drift.values(), default=0.0)
        manifest_candidates.append(
            {
                "seedIndex": index,
                "seedOffsetMeters": [delta_u, delta_v],
                "a800SeedOffsetMeters": list(a800_offset),
                "a180SeedOffsetMeters": list(a180_offset),
                "t401SeedOffsetMeters": list(t401_offset),
                "a500SeedOffsetMeters": list(a500_offset),
                "a300SeedOffsetMeters": list(a300_offset),
                "a700SeedOffsetMeters": list(a700_offset),
                "seedA200RelativeToA100Meters": [
                    float(base_a200["x"]) + delta_u,
                    float(base_a200["y"]) + delta_v,
                ],
                "seedPath": str(seed_path),
                "solverFeasible": True,
                "duplicateSolverPlacement": duplicate,
                "solveSeconds": elapsed,
                "solutionScore": float(selected.get("score", 0.0)),
                "solutionPath": str(solution_path),
                "solvedA200RelativeToA100Meters": [relative_u, relative_v],
                "lockedComponents": list(solver_locked_components),
                "monitoredNonTargetComponents": list(monitored_non_target_components),
                "maximumNonTargetDriftMeters": maximum_non_target_drift,
                "localRepairEligible": maximum_non_target_drift <= 0.001,
                "cadGates": ["A100-A200 leaf B-Rep", "A200-A800 leaf B-Rep"],
            }
        )

    has_feasible_candidate = any(
        item.get("solverFeasible") for item in manifest_candidates
    )
    manifest = {
        "schemaVersion": 1,
        "success": has_feasible_candidate,
        "status": (
            "OFFLINE_REPAIR_CANDIDATES_READY_FOR_A100_A200_BREP_GATE"
            if has_feasible_candidate
            else "NO_SOLVER_FEASIBLE_LOCAL_REPAIR_CANDIDATE"
        ),
        "requestPath": str(request_path),
        "baseLayoutPath": str(base_path),
        "candidateCount": len(manifest_candidates),
        "uniqueSolverPlacementCount": len(seen),
        "productionReady": False,
        "policy": {
            "candidateBudget": len(a200_offsets),
            "a200PreservedForSpecializedRepair": preserve_a200,
            "solverHardConstraintsRequired": True,
            "firstCadGate": "A100-A200 leaf B-Rep",
            "stopAtFirstPassingCandidate": True,
            "runRemainingConditionalBrepOnlyAfterFirstGatePasses": True,
            "lockNonTargetFunctionalComponents": True,
            "monitorAllNonTargetComponents": True,
            "maximumAllowedNonTargetDriftMeters": 0.001,
            "maximumPortalCenterOffsetOverrideMeters": args.maximum_portal_center_offset,
            "coordinatedA800Repair": coordinated_a800_repair,
            "a800SeedOffsetMeters": list(a800_offset),
            "coordinatedA180Repair": coordinated_a180_repair,
            "a180SeedOffsetMeters": list(a180_offset),
            "coordinatedT401Repair": coordinated_t401_repair,
            "t401SeedOffsetMeters": list(t401_offset),
            "coordinatedA500Repair": coordinated_a500_repair,
            "a500SeedOffsetMeters": list(a500_offset),
            "coordinatedA300Repair": coordinated_a300_repair,
            "a300SeedOffsetMeters": list(a300_offset),
            "coordinatedA700Repair": coordinated_a700_repair,
            "a700SeedOffsetMeters": list(a700_offset),
        },
        "candidates": manifest_candidates,
    }
    manifest_path = output_dir / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(manifest, ensure_ascii=False, indent=2))
    return 0 if manifest["success"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
